// Diff coverage gate: lines the PR adds or changes in instrumented source must be
// at least DIFF_COVERAGE_MIN% (default 80) covered.
// Usage: node scripts/ci/diff-coverage.mjs <base-ref> [coverage/lcov.info]
// Env: DIFF_COVERAGE_MIN, COVERAGE_EXEMPT=true to report without failing
// (CI sets it from the `coverage-exempt` PR label).
//
// What counts: files under src/, open-sse/, cli/ with a JS/TS extension, minus tests,
// .d.ts, cli/dist and the generated providers/registry/index.js. A changed line counts
// only if lcov reports it as executable (has a DA record): blank lines, comments and
// type-only lines are ignored. A gated file missing from the report counts as uncovered.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const CODE_EXT = /\.[cm]?[jt]sx?$/;
const INCLUDE = /^(src|open-sse|cli)\//;
const EXCLUDE = [
  /(^|\/)node_modules\//,
  /^cli\/dist\//,
  /\.d\.ts$/,
  /\.(test|spec)\.[cm]?[jt]sx?$/,
  /^open-sse\/providers\/registry\/index\.js$/, // generated by scripts/migrate-registry.mjs
];

export function isGated(file) {
  return INCLUDE.test(file) && CODE_EXT.test(file) && !EXCLUDE.some((re) => re.test(file));
}

/** Parse `git diff -U0` output into Map<file, Set<newLineNumber>> of added/changed lines. */
export function parseDiff(diff) {
  const out = new Map();
  let file = null;
  for (const line of diff.split("\n")) {
    if (line.startsWith("+++ ")) {
      const p = line.slice(4).trim();
      file = p === "/dev/null" ? null : p.replace(/^b\//, "");
      if (file && !out.has(file)) out.set(file, new Set());
      continue;
    }
    const m = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/.exec(line);
    if (m && file) {
      const start = Number(m[1]);
      const count = m[2] === undefined ? 1 : Number(m[2]);
      for (let i = 0; i < count; i++) out.get(file).add(start + i);
    }
  }
  return out;
}

/** Parse lcov into Map<file, Map<line, hits>> with repo-relative paths. */
export function parseLcov(text, root = process.cwd()) {
  const out = new Map();
  let cur = null;
  for (const line of text.split("\n")) {
    if (line.startsWith("SF:")) {
      let f = line.slice(3).trim();
      if (f.startsWith(root + "/")) f = f.slice(root.length + 1);
      cur = new Map();
      out.set(f, cur);
    } else if (line.startsWith("DA:") && cur) {
      const [ln, hits] = line.slice(3).split(",");
      const n = Number(ln);
      cur.set(n, Math.max(cur.get(n) ?? 0, Number(hits)));
    } else if (line === "end_of_record") cur = null;
  }
  return out;
}

/** Returns { files: [{ file, total, covered, uncovered, missing? }], total, covered, pct }. */
export function computeDiffCoverage(changed, lcov) {
  const files = [];
  let total = 0;
  let covered = 0;
  for (const [file, lines] of changed) {
    if (!isGated(file) || !lines.size) continue;
    const da = lcov.get(file);
    if (!da) {
      const uncovered = [...lines].sort((a, b) => a - b);
      files.push({ file, total: lines.size, covered: 0, uncovered, missing: true });
      total += lines.size;
      continue;
    }
    const exec = [...lines].filter((l) => da.has(l)).sort((a, b) => a - b);
    if (!exec.length) continue;
    const uncovered = exec.filter((l) => da.get(l) === 0);
    files.push({ file, total: exec.length, covered: exec.length - uncovered.length, uncovered });
    total += exec.length;
    covered += exec.length - uncovered.length;
  }
  return { files, total, covered, pct: total ? (covered / total) * 100 : 100 };
}

/** Collapse [1,2,3,7,9,10] into "1-3, 7, 9-10". */
export function ranges(lines) {
  const parts = [];
  for (let i = 0; i < lines.length; i++) {
    let j = i;
    while (j + 1 < lines.length && lines[j + 1] === lines[j] + 1) j++;
    parts.push(i === j ? `${lines[i]}` : `${lines[i]}-${lines[j]}`);
    i = j;
  }
  return parts.join(", ");
}

function main() {
  const base = process.argv[2];
  const lcovFile = process.argv[3] ?? "coverage/lcov.info";
  const min = Number(process.env.DIFF_COVERAGE_MIN ?? 80);
  const exempt = process.env.COVERAGE_EXEMPT === "true";
  if (!base) {
    console.error("usage: diff-coverage.mjs <base-ref> [lcov.info]");
    process.exit(2);
  }
  if (!existsSync(lcovFile)) {
    console.log(`## Diff coverage\n\n_No ${lcovFile}; cannot check._`);
    process.exit(1);
  }
  const mergeBase = execFileSync("git", ["merge-base", base, "HEAD"], { encoding: "utf8" }).trim();
  const diff = execFileSync(
    "git",
    ["diff", "-U0", "--no-color", "--no-renames", "--no-ext-diff", mergeBase, "HEAD"],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  const res = computeDiffCoverage(parseDiff(diff), parseLcov(readFileSync(lcovFile, "utf8")));
  const ok = res.pct >= min;
  const out = ["## Diff coverage", ""];
  if (!res.total) out.push("_No executable changed lines in covered source._");
  else {
    out.push(
      `**${res.pct.toFixed(1)}%** of changed executable lines covered (${res.covered} / ${res.total}), minimum ${min}%.`,
    );
    const bad = res.files.filter((f) => f.uncovered.length);
    if (bad.length) {
      out.push("", "| File | Covered | Uncovered changed lines |", "|---|---:|---|");
      for (const f of bad)
        out.push(
          `| \`${f.file}\`${f.missing ? " (not in report)" : ""} | ${f.covered} / ${f.total} | ${ranges(f.uncovered)} |`,
        );
    }
  }
  if (!ok && exempt)
    out.push("", "> Below the minimum, but the PR has the `coverage-exempt` label.");
  else if (!ok)
    out.push(
      "",
      "> Failing. Add tests, or (maintainers) add the `coverage-exempt` label with a reason in the PR body. See REVIEW.md.",
    );
  console.log(out.join("\n"));
  process.exit(ok || exempt ? 0 : 1);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
