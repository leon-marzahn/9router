// Tests must never touch the real ~/.9router (DB, usage, logs). Each run gets a
// throwaway home: DATA_DIR for the DB layer, HOME/APPDATA for modules that
// resolve ~/.9router (or ~/.codex etc.) via os.homedir() directly.
